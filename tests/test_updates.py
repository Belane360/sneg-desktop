import hashlib
import io
import json
from pathlib import Path
import subprocess
import sys
from zipfile import ZipFile
import pytest
from sneg import updates


def archive(files):
    buffer=io.BytesIO()
    with ZipFile(buffer,'w') as z:
        for name,text in files.items():z.writestr(name,text)
    return buffer.getvalue()


def payload():
    return archive({'main.py':'', 'requirements.txt':Path('requirements.txt').read_text(),
                    'sneg/__init__.py':"__version__='99.0.0'",
                    'sneg/app.py':'def main(): return 0'})


def fake_release(monkeypatch,body,checksum=None):
    digest=checksum or hashlib.sha256(body).hexdigest()
    monkeypatch.setattr(updates,'download',lambda url,*a:digest.encode() if url=='checksum' else body)
    return {'version':'99.0.0','checksum_url':'checksum','url':'archive'}


def test_verified_stage_then_activation_preserves_previous(monkeypatch,tmp_path):
    version=updates.prepare_update(fake_release(monkeypatch,payload()),tmp_path)
    assert not (tmp_path/'active.json').exists()
    updates.atomic_json(tmp_path/'active.json',{'version':'0.4.1'})
    updates.activate(version,tmp_path)
    assert json.loads((tmp_path/'active.json').read_text())=={'version':'99.0.0','previous':'0.4.1'}
    assert (tmp_path/'versions/99.0.0/sneg/app.py').exists()


def test_checksum_failure_keeps_current_version(monkeypatch,tmp_path):
    updates.atomic_json(tmp_path/'active.json',{'version':'0.4.1'})
    with pytest.raises(ValueError,match='сумма'):
        updates.prepare_update(fake_release(monkeypatch,payload(),'0'*64),tmp_path)
    assert json.loads((tmp_path/'active.json').read_text())['version']=='0.4.1'
    assert not (tmp_path/'versions/99.0.0').exists()


@pytest.mark.parametrize('name',['../escape.py','/absolute.py','sneg/../../escape.py','sneg\\escape.py'])
def test_zip_paths_cannot_escape_destination(tmp_path,name):
    with pytest.raises(ValueError):updates.safe_extract(archive({name:'bad'}),tmp_path)
    assert not list(tmp_path.iterdir())


def test_changed_dependencies_require_full_installer(monkeypatch,tmp_path):
    data=archive({'main.py':'','requirements.txt':'SomethingElse==1',
                  'sneg/__init__.py':"__version__='99.0.0'",'sneg/app.py':''})
    with pytest.raises(ValueError,match='компоненты'):
        updates.prepare_update(fake_release(monkeypatch,data),tmp_path)
    assert not (tmp_path/'active.json').exists()


def test_broken_release_cannot_be_activated(monkeypatch,tmp_path):
    data=archive({'main.py':'','requirements.txt':Path('requirements.txt').read_text(),
                  'sneg/__init__.py':"__version__='99.0.0'",'sneg/app.py':'raise RuntimeError("broken")'})
    with pytest.raises(subprocess.CalledProcessError):
        updates.prepare_update(fake_release(monkeypatch,data),tmp_path)
    assert not (tmp_path/'active.json').exists()


def test_github_latest_ignores_older_versions(monkeypatch):
    data={'tag_name':'v0.3.1','assets':[]}
    monkeypatch.setattr(updates,'download',lambda *a:json.dumps(data).encode())
    assert updates.latest_release() is None


def test_bootstrap_runs_new_version_and_rolls_back_failure(tmp_path):
    import os
    data_home=tmp_path/'Library/Application Support' if sys.platform=='darwin' else tmp_path
    root=data_home/'Sneg/updates'
    target=root/'versions/99.0.0/sneg';target.mkdir(parents=True)
    (target/'__init__.py').write_text("__version__='99.0.0'")
    (target/'app.py').write_text('def main():\n print("UPDATED_RUNNING"); return 0')
    updates.atomic_json(root/'active.json',{'version':'99.0.0','previous':None})
    # Stub bundled app so a rollback does not start an actual UI in this test.
    bundle=tmp_path/'bundle';(bundle/'sneg').mkdir(parents=True)
    (bundle/'main.py').write_bytes(Path('main.py').read_bytes())
    (bundle/'sneg/__init__.py').write_text("__version__='0.4.1'")
    (bundle/'sneg/updates.py').write_bytes(Path('sneg/updates.py').read_bytes())
    (bundle/'sneg/app.py').write_text('def main():\n print("BUNDLED_RUNNING"); return 0')
    env={**os.environ,'XDG_DATA_HOME':str(tmp_path),'LOCALAPPDATA':str(tmp_path),'HOME':str(tmp_path)}
    result=subprocess.run([sys.executable,str(bundle/'main.py')],env=env,capture_output=True,text=True,check=True)
    assert 'UPDATED_RUNNING' in result.stdout
    (target/'app.py').write_text('raise RuntimeError("startup failed")')
    # Remove probe-generated bytecode before rewriting the synthetic module.
    import shutil
    shutil.rmtree(target/'__pycache__',ignore_errors=True)
    result=subprocess.run([sys.executable,str(bundle/'main.py')],env=env,capture_output=True,text=True,check=True)
    assert 'BUNDLED_RUNNING' in result.stdout
    assert json.loads((root/'active.json').read_text())['version']=='0.4.1'
    assert 'startup failed' in (root/'last-error.log').read_text()
